function randomStream(seed) {
  let value = (Number(seed) >>> 0) || 0x175b0ace;
  return () => {
    value = (Math.imul(value, 1664525) + 1013904223) >>> 0;
    return value / 0x100000000;
  };
}
function shuffled(items, random) {
  const result = [...items];
  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    [result[i], result[j]] = [result[j], result[i]];
  }
  return result;
}
/** The tour seed fixes its shuffled deck across retries and saved checkpoints.
 * Every question appears once before the deck repeats, independently of roads.
 */
export function questionForStage(routeIndex, _road = 'scenic', seed = 175) {
  const stage = Math.max(0, Math.trunc(Number(routeIndex) || 0));
  const random = randomStream(seed);
  const unit = shuffled(QUESTIONS.filter(item => item.category === 'ギャルインザミックス'), random);
  const culture = shuffled(QUESTIONS.filter(item => item.category !== 'ギャルインザミックス'), random);
  // A twelve-road tour draws eleven unit questions and one culture question.
  const deck = [...shuffled([...unit.slice(0, 11), culture[0]], random), ...shuffled([...unit.slice(11), ...culture.slice(1)], random)];
  const question = deck[stage % deck.length];
  const choices = shuffled(question.choices.map((text, index) => ({text, index})), randomStream((Number(seed) >>> 0) ^ Math.imul(stage + 1, 0x9e3779b1)));
  return {...question, choices: choices.map(choice => choice.text), answer: choices.findIndex(choice => choice.index === question.answer)};
}
